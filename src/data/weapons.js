export function getWeaponsByRarity(rarity) {
  return Object.values(WEAPONS).filter(w => w.rarity === rarity);
}

export function getRandomWeapon(minRarity = 'common') {
  const rarityOrder = ['common', 'uncommon', 'rare', 'epic', 'legendary'];
  const minIdx = rarityOrder.indexOf(minRarity);
  const available = Object.values(WEAPONS).filter(w => {
    return rarityOrder.indexOf(w.rarity) >= minIdx;
  });
  if (available.length === 0) return { ...WEAPONS.pistol };
  return { ...available[Math.floor(Math.random() * available.length)] };
}